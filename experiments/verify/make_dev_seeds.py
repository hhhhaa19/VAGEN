"""Development seeds for G, R, D1 and O, kept apart from the test set.

Test is the 256 seeds of val_sokoban_vision_sr_paper.yaml. Dev takes seeds from 12000 on
under the same rules the test manifest is checked against in
tests/test_sokoban_map_partition.py: the seed's own room (no retry walk) is in the eval
partition and solvable in 1-5 steps. Rooms equal to a test room or to an earlier dev room
are dropped, so tuning on dev never sees a test level.

Usage (CPU only, a few seconds):
    python experiments/verify/make_dev_seeds.py [size] [first_seed]
Writes examples/train/sokoban/val_sokoban_vision_sr_paper_dev.yaml.
"""
import re
import sys
from pathlib import Path

import yaml
from gym_sokoban.envs.room_utils import generate_room

from vagen.envs.sokoban.patch_sokoban_env import _room_matches_partition, get_shortest_action_path
from vagen.envs.sokoban.utils.seeding import set_seed

ROOT = Path(__file__).resolve().parents[2]
TEST = ROOT / "examples/train/sokoban/val_sokoban_vision_sr_paper.yaml"
DEV = ROOT / "examples/train/sokoban/val_sokoban_vision_sr_paper_dev.yaml"


def room(seed):
    """The fingerprint of the seed's room, or None if it fails the test-set rules."""
    with set_seed(seed):
        fixed, state, _ = generate_room(dim=(6, 6), num_steps=20, num_boxes=1, second_player=False)
    if not 1 <= len(get_shortest_action_path(fixed, state, MAX_DEPTH=200)) <= 5:
        return None
    if not _room_matches_partition(fixed, state, "eval", 4, 0):
        return None
    return fixed.tobytes() + state.tobytes()


def main():
    size = int(sys.argv[1]) if len(sys.argv) > 1 else 128
    seed = int(sys.argv[2]) if len(sys.argv) > 2 else 12000
    text = TEST.read_text()
    spec = yaml.safe_load(text)["envs"][0]
    test_seeds = spec["seed_list"]
    assert spec["max_turns"] and max(test_seeds) < seed, "dev must start after the test seeds"

    seen = {room(s) for s in test_seeds}
    assert None not in seen and len(seen) == len(test_seeds), "test manifest changed"
    chosen, duplicates = [], 0
    while len(chosen) < size:
        found = room(seed)
        if found is not None:
            if found in seen:
                duplicates += 1
            else:
                seen.add(found)
                chosen.append(seed)
        seed += 1

    rows = ",\n".join(
        "      " + ", ".join(str(s) for s in chosen[i:i + 16]) for i in range(0, size, 16)
    )
    out = re.sub(r"\A(?:#.*\n)+", "", text)  # the test file's own header comment
    out = re.sub(r"n_envs: \d+", f"n_envs: {size}", out, count=1)
    out = re.sub(r"seed_list: \[.*?\]", f"seed_list: [\n{rows},\n    ]", out, count=1, flags=re.S)
    header = (f"# Development set for the verification settings: {size} eval-partition seeds\n"
              f"# from {chosen[0]} to {chosen[-1]}, no room equal to a test room. Generated by\n"
              f"# experiments/verify/make_dev_seeds.py; everything except the seeds is the test config.\n")
    DEV.write_text(header + out)
    assert yaml.safe_load(DEV.read_text())["envs"][0]["seed_list"] == chosen
    print(f"dev seeds {chosen[0]}..{chosen[-1]}; {duplicates} dropped as repeats; wrote {size} to {DEV}")


if __name__ == "__main__":
    main()
